package com.nbicocchi.app.utils;

public class MathUtils {

    // funzione semplice: somma due numeri
    public static int add(int a, int b) {
        return a + b;
    }

    // funzione esempio: verifica se un numero è pari
    public static boolean isEven(int n) {
        return n % 2 == 0;
    }
}